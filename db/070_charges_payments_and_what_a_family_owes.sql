-- ---------------------------------------------------------------------------
--  7. Discounts and waivers on a charge that already exists
--
--  A DISCOUNT AND A WAIVER ARE DIFFERENT THINGS AND THE MASJID SHOULD SEE
--  WHICH IS WHICH. A discount is the published rule applied — the second
--  child pays less because that is the policy. A waiver is a decision about
--  one family, usually hardship, usually taken by somebody who should be
--  accountable for it. Both reduce the bill; only one of them is a judgement.
--  Keeping them in separate columns is what lets the Annual report tell the
--  trustees "£1,240 of discount and £680 written off", which is a sentence
--  they can act on, instead of one number nobody can question.
-- ---------------------------------------------------------------------------
create or replace function public.adjust_madrasah_charge(p jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_masjid uuid := public.current_masjid();
  v_id     uuid := nullif(p->>'id', '')::uuid;
  v_row    public.madrasah_charges%rowtype;
  v_disc   integer;
  v_waive  integer;
  v_dnote  text;
  v_wnote  text;
  v_net    integer;
begin
  if not public.verified_admin() then
    raise exception 'Only an administrator who has completed two-step may change a charge.'
      using errcode = '42501';
  end if;

  select * into v_row from public.madrasah_charges
   where id = v_id and masjid_id = v_masjid;
  if v_row.id is null then
    raise exception 'There is no such charge at this masjid.' using errcode = 'no_data_found';
  end if;

  v_disc  := greatest(coalesce(nullif(p->>'discount_p', '')::integer, v_row.discount_p), 0);
  v_waive := greatest(coalesce(nullif(p->>'waived_p',   '')::integer, v_row.waived_p),   0);

  --  AN ABSENT KEY MEANS "LEAVE IT ALONE". 058 set this rule for class lists
  --  and it matters more here. The amounts already followed it; the notes did
  --  not, so the Discounts screen — which sends only the waiver fields —
  --  silently wiped "Sibling discount" off every charge it touched, leaving
  --  an unexplained discount line in the annual report. That is precisely the
  --  thing the compulsory waiver reason exists to prevent, arrived at from
  --  the other direction.
  v_dnote := case when p ? 'discount_note'
                  then nullif(btrim(coalesce(p->>'discount_note', '')), '')
                  else v_row.discount_note end;
  v_wnote := case when p ? 'waiver_note'
                  then nullif(btrim(coalesce(p->>'waiver_note', '')), '')
                  else v_row.waiver_note end;

  if v_disc + v_waive > v_row.gross_p then
    raise exception 'That is more than the charge itself. The bill is %, and you have taken % off it.',
      '£' || to_char(v_row.gross_p / 100.0, 'FM999999990.00'),
      '£' || to_char((v_disc + v_waive) / 100.0, 'FM999999990.00')
      using errcode = 'check_violation';
  end if;

  --  A WRITE-OFF HAS TO SAY WHY. Not politeness: a waiver is the masjid
  --  giving away its own income, the trustees see the total in the annual
  --  report, and an unexplained line there is one somebody has to go and
  --  reconstruct from memory a year later.
  if v_waive > 0 and v_wnote is null then
    raise exception 'Say why the fee is being waived. It goes to the trustees in the annual report.'
      using errcode = 'check_violation';
  end if;

  update public.madrasah_charges
     set discount_p = v_disc, discount_note = v_dnote,
         waived_p = v_waive, waiver_note = v_wnote
   where id = v_id and masjid_id = v_masjid;

  insert into public.admin_audit (masjid_id, actor, action, detail)
  values (v_masjid, auth.uid(), 'madrasah_charge_adjusted',
          jsonb_build_object('id', v_id, 'household', v_row.household_id,
                             'discount_p', v_disc, 'waived_p', v_waive,
                             'was_discount_p', v_row.discount_p,
                             'was_waived_p', v_row.waived_p));

  --  READ BACK, not recomputed. net_p is a generated column and this file's
  --  header says a second code path for it cannot exist — so this function
  --  should not be one, even though its arithmetic happens to agree today.
  select net_p into v_net from public.madrasah_charges where id = v_id;
  return jsonb_build_object('ok', true, 'net_p', v_net);
end $fn$;

