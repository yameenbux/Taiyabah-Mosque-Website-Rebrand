-- ===========================================================================
--  CHECKS
-- ===========================================================================

--  #1  net_p is computed by the database, not by whoever is inserting.
do $c1$
declare v_gen text;
begin
  select attgenerated into v_gen from pg_attribute
   where attrelid = 'public.madrasah_charges'::regclass and attname = 'net_p';
  if coalesce(v_gen, '') <> 's' then
    raise exception 'CHECK 1 FAILED: madrasah_charges.net_p is not a stored generated column. A screen that forgets to subtract a waiver would report a different total from the annual report.';
  end if;
  raise notice 'CHECK 1 passed: what a family owes is computed by Postgres.';
end $c1$;

--  #2  A refund cannot be stored as money coming in, and a discount cannot
--      exceed the bill. Both asserted against the CONSTRAINTS, not through
--      the functions — going through the functions would be stopped by
--      verified_admin() first and the check would pass without ever
--      exercising the rule.
--
--      THE THROWAWAY MASJID IS WRITTEN OUT IN FULL, and it was not always.
--      The first version of this block inserted a masjid with a name and
--      nothing else, which is all the local harness needed. Production's
--      `masjids` has THREE not-null columns with no default — slug, name
--      and town — so the insert would have raised a not_null_violation and
--      taken the whole migration down with it, on a file that had passed
--      every time it was run. The harness was a smaller table wearing the
--      same name. A check is only as honest as the schema it ran against.
--
--      The slug is random because slug is unique, and a migration that can
--      only ever be applied once is a migration you cannot re-apply after
--      fixing something else in it. Everything here is deleted before the
--      block ends, and the cascade on masjid_id takes the household.
do $c2$
declare
  v_m uuid;
  v_h uuid;
  v_bad boolean;
begin
  insert into public.masjids (slug, name, town)
  values ('check2-' || replace(gen_random_uuid()::text, '-', ''),
          'CHECK-2 throwaway', 'Nowhere')
  returning id into v_m;
  insert into public.madrasah_households (masjid_id, reference, name)
  values (v_m, 'MF-9999', 'Check 2') returning id into v_h;

  v_bad := false;
  begin
    insert into public.madrasah_payments (masjid_id, household_id, kind, method, amount_p)
    values (v_m, v_h, 'refund', 'bank', 5000);
    v_bad := true;
  exception when check_violation then null;
  end;
  if v_bad then
    raise exception 'CHECK 2 FAILED: a refund was stored as a positive amount. It would have increased what the family had paid.';
  end if;

  v_bad := false;
  begin
    insert into public.madrasah_charges
      (masjid_id, household_id, description, gross_p, discount_p, waived_p)
    values (v_m, v_h, 'Check 2', 1000, 600, 600);
    v_bad := true;
  exception when check_violation then null;
  end;
  if v_bad then
    raise exception 'CHECK 2 FAILED: relief of £12 was allowed against a bill of £10. The family would have gone into credit and dropped off the Outstanding screen.';
  end if;

  --  And the honest half: a correct row must still go in, or the two
  --  rejections above prove only that the table refuses everything.
  insert into public.madrasah_payments (masjid_id, household_id, kind, method, amount_p)
  values (v_m, v_h, 'refund', 'bank', -5000);
  insert into public.madrasah_charges
    (masjid_id, household_id, description, gross_p, discount_p, waived_p)
  values (v_m, v_h, 'Check 2', 1000, 250, 250);

  delete from public.madrasah_charges  where masjid_id = v_m;
  delete from public.madrasah_payments where masjid_id = v_m;
  delete from public.masjids           where id = v_m;
  raise notice 'CHECK 2 passed: the sign of a refund and the size of a discount are enforced by the table.';
end $c2$;

--  #3  Running the generator twice does not charge twice.
--      Somebody will press it twice. The index is what makes that harmless.
do $c3$
declare v_ok boolean;
begin
  select exists (
    select 1 from pg_indexes
     where schemaname = 'public'
       and indexname = 'madrasah_charge_one_per_pupil_per_term_idx'
       and indexdef ilike '%UNIQUE%')
    into v_ok;
  if not v_ok then
    raise exception 'CHECK 3 FAILED: nothing stops a term being charged twice.';
  end if;
  raise notice 'CHECK 3 passed: raising charges for a term is safe to press twice.';
end $c3$;

--  #4  Deleting a pupil, or a family, must never delete the money record.
--      058's rule about safeguarding, applied to the charity's own accounts,
--      which are on a six-year clock and not the pupil's three-year one.
do $c4$
declare v_rule text; v_bad text := '';
begin
  select confdeltype::text into v_rule from pg_constraint
   where conrelid = 'public.madrasah_charges'::regclass and contype = 'f'
     and confrelid = 'public.madrasah_pupils'::regclass;
  if coalesce(v_rule, '') <> 'n' then
    v_bad := v_bad || 'charges->pupils is not SET NULL. ';
  end if;

  foreach v_rule in array array[
    (select confdeltype::text from pg_constraint
      where conrelid = 'public.madrasah_charges'::regclass and contype='f'
        and confrelid = 'public.madrasah_households'::regclass),
    (select confdeltype::text from pg_constraint
      where conrelid = 'public.madrasah_payments'::regclass and contype='f'
        and confrelid = 'public.madrasah_households'::regclass)] loop
    if coalesce(v_rule, '') <> 'r' then
      v_bad := v_bad || 'a money table does not RESTRICT deletion of the family it belongs to. ';
    end if;
  end loop;

  if v_bad <> '' then
    raise exception 'CHECK 4 FAILED: %The three-year pupil purge would take the charity''s financial records with it.', v_bad;
  end if;
  raise notice 'CHECK 4 passed: deleting people never deletes the money record.';
end $c4$;

--  #5  Every function here is administrators only. Line-based — 065.
do $c5$
declare v_fn text; v_def text; v_line text; v_found boolean;
begin
  foreach v_fn in array array['raise_madrasah_charges', 'madrasah_fee_balances',
                              'madrasah_household_statement', 'record_madrasah_payment',
                              'delete_madrasah_payment', 'adjust_madrasah_charge',
                              'cancel_madrasah_charge', 'add_madrasah_charge'] loop
    select pg_get_functiondef(p.oid) into v_def
      from pg_proc p join pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'public' and p.proname = v_fn limit 1;
    if v_def is null then
      raise exception 'CHECK 5 FAILED: public.%() does not exist.', v_fn;
    end if;
    v_found := false;
    foreach v_line in array string_to_array(v_def, E'\n') loop
      if btrim(v_line) not like '--%' and v_line like '%public.verified_admin()%' then
        v_found := true; exit;
      end if;
    end loop;
    if not v_found then
      raise exception 'CHECK 5 FAILED: public.%() never calls public.verified_admin() in live code. A teacher could read what every family at the masjid owes.', v_fn;
    end if;
  end loop;
  raise notice 'CHECK 5 passed: the whole ledger is administrators only.';
end $c5$;

