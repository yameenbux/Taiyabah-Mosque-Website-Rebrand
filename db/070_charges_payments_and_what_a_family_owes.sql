--  Charging one family something one-off: an admission fee, or a balance
--  brought over from the old system.
create or replace function public.add_madrasah_charge(p jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_masjid uuid := public.current_masjid();
  v_house  uuid := nullif(p->>'household_id', '')::uuid;
  v_desc   text := btrim(coalesce(p->>'description', ''));
  v_gross  integer;
  v_pupil  uuid;
  v_row    public.madrasah_charges%rowtype;
begin
  if not public.verified_admin() then
    raise exception 'Only an administrator who has completed two-step may add a charge.'
      using errcode = '42501';
  end if;
  if not exists (select 1 from public.madrasah_households
                  where id = v_house and masjid_id = v_masjid) then
    raise exception 'There is no such family at this masjid.' using errcode = 'no_data_found';
  end if;
  if v_desc = '' then
    raise exception 'Say what the charge is for.' using errcode = 'check_violation';
  end if;

  begin
    v_gross := (p->>'gross_p')::integer;
  exception when others then
    raise exception 'That amount is not a number of pence.' using errcode = 'check_violation';
  end;
  if v_gross is null or v_gross <= 0 then
    raise exception 'A charge of nothing is not a charge.' using errcode = 'check_violation';
  end if;

  --  A PUPIL ID IS CHECKED AGAINST THIS MASJID AND THIS FAMILY. The foreign
  --  key only requires the child to exist somewhere, so without this a charge
  --  could be stamped with another masjid's pupil, or with a child from a
  --  different family — and madrasah_household_statement() would then show it
  --  on the wrong family's account.
  v_pupil := nullif(p->>'pupil_id', '')::uuid;
  if v_pupil is not null and not exists (
       select 1 from public.madrasah_pupils
        where id = v_pupil and masjid_id = v_masjid and household_id = v_house) then
    raise exception 'That child is not in this family.' using errcode = 'no_data_found';
  end if;

  insert into public.madrasah_charges
    (masjid_id, household_id, pupil_id, kind, description, gross_p, charged_on, created_by)
  values (v_masjid, v_house, v_pupil,
          coalesce(nullif(btrim(coalesce(p->>'kind', '')), ''), 'other'),
          v_desc, v_gross,
          coalesce(nullif(p->>'charged_on', '')::date, current_date), auth.uid())
  returning * into v_row;

  insert into public.admin_audit (masjid_id, actor, action, detail)
  values (v_masjid, auth.uid(), 'madrasah_charge_added',
          jsonb_build_object('id', v_row.id, 'household', v_house,
                             'gross_p', v_gross, 'kind', v_row.kind));

  return jsonb_build_object('id', v_row.id);
end $fn$;

