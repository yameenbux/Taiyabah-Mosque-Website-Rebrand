#!/usr/bin/env python3
"""Write the seven Fees screens from one shell.

WHY A GENERATOR AND NOT SEVEN HAND-WRITTEN FILES
------------------------------------------------
Every portal screen carries the whole sign-in shell — loading, sign in, the
two-step challenge, the enrolment QR — copied inline. That is the house
pattern and it is not wrong: each screen is standalone, with no build step
between the file and the browser.

At seven screens in one section it stops being copying and starts being
drift. The Fees screens are the ones that decide who may see what a family
owes, and seven hand-copied sign-in shells is seven places for that to be
subtly different. So the shell is taken from portal/classes/index.html and
the seven files are written from it.

This is a GENERATOR, not a build step. It runs when somebody adds a screen
or changes the shell; the files it writes are committed and served exactly
as they are, and nothing at run time depends on this script existing. That
is the difference from build.py, which must be run before every push.

    python3 tools/build_fees_screens.py

It refuses to run if the shell it copies from has moved, rather than writing
seven broken screens.
"""

