def read_shell():
    if not os.path.exists(SHELL):
        sys.exit("The shell screen %s is missing. Nothing written." % SHELL)
    src = open(SHELL, encoding="utf-8").read()

    for marker in ('<style>', '<body>', 'id="cl-panel"', 'id="app-signout"'):
        if marker not in src:
            sys.exit("The shell has changed — %s is gone. Nothing written, so "
                     "that seven screens are not written wrongly." % marker)

    i = src.index("<style>")
    head = src[:i]

    b = src.index("<body>")
    sec = src.index('<section class="bk" id="cl-panel" hidden>')
    shell_top = src[b:sec]

    tail_at = src.rindex("</section>")
    tail = src[tail_at + len("</section>"):]
    return head, shell_top, tail


def rel(depth):
    """How many ../ a file at this depth needs to reach the web root."""
    return "../" * depth


