def build():
    head, shell_top, tail = read_shell()
    written = []

    for s in SCREENS:
        r = rel(s["depth"])
        gate = "gate.js" if s["depth"] == 2 else "../gate.js"
        css = "fees.css" if s["depth"] == 2 else "../fees.css"
        nav = r[:-3] + "nav.js" if s["depth"] > 2 else "../nav.js"

        # head: retitle, repoint, and swap the inline <style> for the shared
        # stylesheet. The token block is identical on every screen, so seven
        # copies of it would be seven chances for the plum to drift.
        h = head
        h = re.sub(r"<title>.*?</title>",
                   "<title>%s &mdash; Fees &mdash; Madrasah &mdash; Taiyabah Masjid</title>"
                   % s["title"], h, flags=re.S)
        # The shell's path comment describes /portal/staff/. Left as it is,
        # every generated screen would carry a confident statement about its
        # own depth that is wrong for six of the seven — which is worse than
        # no comment, because somebody fixing a path would trust it.
        h = re.sub(r"<!-- =+\n     THIS SCREEN IS TWO FOLDERS DOWN.*?-->",
                   PATH_NOTE % (s["depth"], "../" * s["depth"],
                                "../" if s["depth"] == 2 else "../../"),
                   h, flags=re.S)
        h = h.replace("../../fonts/", r + "fonts/")
        h = h.replace("../../admin/", r + "admin/")
        h = h.replace('src="../nav.js"', 'src="%s"' % nav)
        #  Furniture first, section second. admin/screen.css carries the
        #  tokens, the sign-in panel, the buttons and the fields; fees.css
        #  carries what is about money. A section sheet may override
        #  furniture, so it has to come after it.
        h = h.rstrip() + ('\n<link rel="stylesheet" href="%sadmin/screen.css">'
                          '\n<link rel="stylesheet" href="%s">\n</head>\n'
                          % (r, css))
        h = h.replace("</head>\n<link", "<link")          # keep one </head>

        top = shell_top
        top = re.sub(r"<h1>.*?</h1>", "<h1>%s</h1>" % s["h1"], top, flags=re.S)
        top = re.sub(r"<h1>%s</h1>\s*\n\s*<p>.*?</p>" % re.escape(s["h1"]),
                     "<h1>%s</h1>\n      <p>%s</p>" % (s["h1"], s["lead"]),
                     top, flags=re.S)
        back = "../" if s["depth"] == 2 else "../"
        top = re.sub(r'<a class="back" href="[^"]*">.*?</a>',
                     '<a class="back" href="%s">&larr; Back to %s</a>'
                     % (back, "the madrasah portal" if s["depth"] == 2 else "Fees"),
                     top, flags=re.S)
        top = top.replace('<section class="bk" id="cl-panel" hidden>', "")
        top = re.sub(r"<!-- The staff themselves\..*?-->", PANEL_NOTE, top, flags=re.S)

        t = tail
        t = t.replace("../../admin/", r + "admin/")
        t = t.replace('<script src="app.js"></script>',
                      '<script src="%s"></script>\n<script src="app.js"></script>' % gate)

        html = (h + top
                + '      <section class="bk" id="fx-panel" hidden>\n'
                + s["body"]
                + "      </section>\n" + t)

        folder = os.path.join(ROOT, s["folder"])
        os.makedirs(folder, exist_ok=True)
        open(os.path.join(folder, "index.html"), "w", encoding="utf-8").write(html)

        # config.js is byte-for-byte identical in every portal screen.
        src_cfg = os.path.join(ROOT, "portal", "classes", "config.js")
        open(os.path.join(folder, "config.js"), "w", encoding="utf-8").write(
            open(src_cfg, encoding="utf-8").read())

        written.append((s["folder"], len(html)))

    for folder, n in written:
        print("  %-28s %6d bytes" % (folder + "/index.html", n))
    print("\n%d screens written." % len(written))


if __name__ == "__main__":
    build()
